-- Native ecosystems retain their own manifests, dependency resolution, and source conventions.
local M = {}
local function copy(v)
  if type(v) ~= 'table' then
    return v
  end
  local o = {}
  for k, x in pairs(v) do
    o[k] = copy(x)
  end
  return o
end
local function c_targets(spec)
  local text = { '# Generated by Rivet; extend CMakeLists.txt for custom behavior.' }
  for _, t in ipairs(spec.targets) do
    if t.test then
      text[#text + 1] = 'if(BUILD_TESTING)'
    end
    text[#text + 1] = (t.type == 'executable' and 'add_executable(' or 'add_library(')
      .. t.name
      .. (t.type == 'executable' and '' or ' STATIC')
    for _, p in ipairs(t.sources) do
      text[#text + 1] = '  "${PROJECT_SOURCE_DIR}/' .. p .. '"'
    end
    text[#text + 1] = ')\nset_target_properties('
      .. t.name
      .. ' PROPERTIES C_STANDARD '
      .. spec.standard
      .. ' C_STANDARD_REQUIRED YES C_EXTENSIONS NO)'
    text[#text + 1] = 'target_include_directories('
      .. t.name
      .. ' PUBLIC "${PROJECT_SOURCE_DIR}/include")'
    if #(t.links or {}) > 0 then
      text[#text + 1] = 'target_link_libraries('
        .. t.name
        .. ' PRIVATE '
        .. table.concat(t.links, ' ')
        .. ')'
    end
    if t.test then
      text[#text + 1] = 'add_test(NAME ' .. t.name .. ' COMMAND ' .. t.name .. ')\nendif()'
    end
  end
  text[#text + 1] =
    'find_program(RIVET_CLANG_FORMAT clang-format)\nif(RIVET_CLANG_FORMAT)\n  add_custom_target(format COMMAND "${RIVET_CLANG_FORMAT}" -i'
  for _, t in ipairs(spec.targets) do
    for _, f in ipairs({ 'sources', 'headers' }) do
      for _, p in ipairs(t[f] or {}) do
        text[#text + 1] = '    "${PROJECT_SOURCE_DIR}/' .. p .. '"'
      end
    end
  end
  text[#text + 1] = '    VERBATIM)\nendif()'
  return table.concat(text, '\n') .. '\n'
end
local function swift_manifest(spec)
  local text = {
    '// swift-tools-version: 6.0',
    'import PackageDescription',
    'let package = Package(',
    '    name: "' .. spec.name .. '",',
    '    products: [',
  }
  for _, t in ipairs(spec.targets) do
    if not t.test then
      text[#text + 1] = '        .'
        .. (t.type == 'executable' and 'executable' or 'library')
        .. '(name: "'
        .. t.name
        .. '", targets: ["'
        .. t.name
        .. '"]),'
    end
  end
  text[#text + 1] = '    ],\n    targets: ['
  for _, t in ipairs(spec.targets) do
    local deps = {}
    for _, d in ipairs(t.links or {}) do
      deps[#deps + 1] = '"' .. d .. '"'
    end
    text[#text + 1] = '        .'
      .. (t.test and 'testTarget' or t.type == 'executable' and 'executableTarget' or 'target')
      .. '(name: "'
      .. t.name
      .. '", dependencies: ['
      .. table.concat(deps, ', ')
      .. ']),'
  end
  text[#text + 1] = '    ]\n)\n'
  return table.concat(text, '\n')
end
function M.make(language)
  local function identifier(value, edition)
    return require('rivet.identifiers').validate(language, value, edition)
  end
  local P = {
    label = ({ python = 'Python', rust = 'Rust', swift = 'SwiftPM', c = 'C' })[language],
    profile_fields = { 'kind', 'manager', 'edition', 'standard' },
  }
  P.services = {
    tasks = language == 'c' and 'rivet.cmake' or 'rivet.native_tasks',
    doctor = 'rivet.native_doctor',
    headers = language == 'python' and 'rivet.python_headers' or 'rivet.headers',
    diagnostics = 'rivet.native_diagnostics',
  }
  function P.default_name(folder)
    local name = folder:gsub('[^%w_]', '_'):gsub('_+', '_'):gsub('^_+', '')
    if name == '' or not name:match('^[A-Za-z]') then
      name = 'project_' .. name
    end
    if not pcall(identifier, name) then
      name = 'project_' .. name
    end
    return name
  end
  function P.normalize(opts)
    local s = copy(opts)
    s.schema_version = s.schema_version or 1
    s.language = language
    assert(s.schema_version == 1, 'Unsupported manifest schema')
    s.name = identifier(s.name or 'example', s.edition)
    s.kind = s.kind or 'app'
    assert(
      s.kind == 'app' or s.kind == 'library' or language == 'rust' and s.kind == 'workspace',
      'Choose app, library, or a Rust workspace'
    )
    s.files = s.files or {}
    s.targets = s.targets or {}
    s.module_names = s.module_names or {}
    s.dependencies = s.dependencies or {}
    for _, p in ipairs(s.files) do
      assert(
        p:match('^[%w_./%-]+$') and not p:find('..', 1, true) and p:sub(1, 1) ~= '/',
        'Invalid source path'
      )
    end
    for _, t in ipairs(s.targets) do
      identifier(t.name, s.edition)
      for _, p in ipairs(t.sources or {}) do
        require('rivet.runtime').safe_relative(p)
      end
    end
    s.comment_header = require('rivet.headers').normalize(s.comment_header)
    if language == 'python' then
      s.manager = s.manager or 'python'
      assert(s.manager == 'python' or s.manager == 'uv', 'Choose python or uv')
    end
    if language == 'rust' then
      s.edition = tostring(s.edition or '2024')
      assert(s.edition == '2021' or s.edition == '2024', 'Choose Rust edition 2021 or 2024')
    end
    if language == 'c' then
      s.standard = tonumber(s.standard or 17)
      assert(s.standard == 17 or s.standard == 23 or s.standard == 11, 'Choose C11, C17, or C23')
    end
    return s
  end
  function P.ignore_rules()
    return ({
      python = '/.venv/\n__pycache__/\n*.py[cod]\n*.egg-info/\n/dist/\n/build/\n/.pytest_cache/\n/.ruff_cache/\n',
      rust = '/target/\n',
      swift = '/.build/\n/.swiftpm/\n',
      c = require('rivet.languages.cpp').ignore_rules(),
    })[language] .. '/.cache/\n.DS_Store\n'
  end
  local function add(s, files, path, text, target)
    for _, p in ipairs(s.files) do
      assert(p:lower() ~= path:lower(), 'File already registered: ' .. path)
    end
    s.files[#s.files + 1] = path
    local headers = require(P.services.headers)
    files[path] = headers.accepts(path, '')
        and (headers.render(s.comment_header, { filename = path, project = s.name }) .. text)
      or text
    if target then
      target.sources[#target.sources + 1] = path
    end
  end
  local function target(s, name, kind, test, links)
    identifier(name, s.edition)
    for _, t in ipairs(s.targets) do
      assert(t.name ~= name, 'Target already exists')
    end
    local t = {
      name = name,
      type = kind,
      test = test,
      sources = {},
      headers = {},
      modules = {},
      links = links or {},
      include_dirs = { 'include' },
    }
    s.targets[#s.targets + 1] = t
    return t
  end
  local function generated(s, files, source_only)
    local managed = {}
    if language == 'c' then
      files['cmake/RivetTargets.cmake'] = c_targets(s)
      managed['cmake/RivetTargets.cmake'] = true
    elseif language == 'swift' and not source_only then
      files['Package.swift'] = swift_manifest(s)
      managed['Package.swift'] = true
    end
    for path in pairs(files) do
      local found = false
      for _, p in ipairs(s.files) do
        if p == path then
          found = true
        end
      end
      if not found then
        s.files[#s.files + 1] = path
      end
    end
    table.sort(s.files)
    return { spec = s, files = files, managed = managed }
  end
  function P.plan(opts)
    local s = P.normalize(opts)
    assert(#s.files == 0, 'New projects only')
    local files = {}
    if language == 'python' then
      add(
        s,
        files,
        'pyproject.toml',
        '[build-system]\nrequires = ["setuptools>=77.0.3"]\nbuild-backend = "setuptools.build_meta"\n\n[project]\nname = "'
          .. s.name
          .. '"\nversion = "0.1.0"\nrequires-python = ">=3.11"\ndependencies = []\n'
          .. (s.license and s.license.id ~= 'none' and 'license = "' .. s.license.id .. '"\nlicense-files = ["LICENSE"' .. ((s.license.id == 'Apache-2.0' or s.license.id == 'GPL-3.0-only') and ', "NOTICE"' or '') .. ']\n' or '')
          .. (s.kind == 'app' and '\n[project.scripts]\n' .. s.name .. ' = "' .. s.name .. '.__main__:main"\n' or '')
          .. '\n[tool.setuptools.packages.find]\nwhere = ["src"]\n'
      )
      add(
        s,
        files,
        'src/' .. s.name .. '/__init__.py',
        'def add(a: int, b: int) -> int:\n    return a + b\n'
      )
      if s.kind == 'app' then
        local t = target(s, s.name, 'executable')
        add(
          s,
          files,
          'src/' .. s.name .. '/__main__.py',
          'from . import add\n\ndef main() -> None:\n    print(add(20, 22))\n\nif __name__ == "__main__":\n    main()\n',
          t
        )
      end
      add(
        s,
        files,
        'tests/test_core.py',
        'import unittest\n\nfrom '
          .. s.name
          .. ' import add\n\nclass CoreTests(unittest.TestCase):\n    def test_add(self):\n        self.assertEqual(add(20, 22), 42)\n        self.assertEqual(add(-1, 1), 0)\n\nif __name__ == "__main__":\n    unittest.main()\n'
      )
    elseif language == 'rust' then
      local workspace = s.kind == 'workspace'
      local prefix = workspace and 'crates/' .. s.name .. '/' or ''
      if workspace then
        add(
          s,
          files,
          'Cargo.toml',
          '[workspace]\nmembers = ["crates/' .. s.name .. '"]\nresolver = "3"\n'
        )
      end
      add(
        s,
        files,
        prefix .. 'Cargo.toml',
        '[package]\nname = "'
          .. s.name
          .. '"\nversion = "0.1.0"\nedition = "'
          .. s.edition
          .. '"\n'
          .. (s.license and s.license.id ~= 'none' and 'license = "' .. s.license.id .. '"\n' or '')
          .. '\n[dependencies]\n'
      )
      add(
        s,
        files,
        prefix .. 'src/lib.rs',
        'pub fn add(a: i32, b: i32) -> i32 { a + b }\n\n#[cfg(test)]\nmod tests {\n    use super::add;\n    #[test]\n    fn adds_values() { assert_eq!(add(20, 22), 42); assert_eq!(add(-1, 1), 0); }\n}\n'
      )
      if s.kind ~= 'library' then
        add(
          s,
          files,
          prefix .. 'src/main.rs',
          'fn main() { println!("{}", ' .. s.name .. '::add(20, 22)); }\n',
          target(s, s.name, 'executable')
        )
      end
    elseif language == 'swift' then
      local lib = target(s, s.name .. 'Core', 'static')
      add(
        s,
        files,
        'Sources/' .. lib.name .. '/Core.swift',
        'public func sum(_ a: Int, _ b: Int) -> Int { a + b }\n',
        lib
      )
      if s.kind == 'app' then
        local app = target(s, s.name, 'executable', nil, { lib.name })
        add(
          s,
          files,
          'Sources/' .. app.name .. '/main.swift',
          'import ' .. lib.name .. '\nprint(sum(20, 22))\n',
          app
        )
      end
      local test = target(s, s.name .. 'Tests', 'executable', true, { lib.name })
      add(
        s,
        files,
        'Tests/' .. test.name .. '/CoreTests.swift',
        'import XCTest\n@testable import '
          .. lib.name
          .. '\n\nfinal class CoreTests: XCTestCase {\n    func testAdd() {\n        XCTAssertEqual(sum(20, 22), 42)\n        XCTAssertEqual(sum(-1, 1), 0)\n    }\n}\n',
        test
      )
    else
      local lib = target(s, s.name .. '_core', 'static')
      add(
        s,
        files,
        'include/' .. s.name .. '.h',
        '#ifndef '
          .. s.name:upper()
          .. '_H\n#define '
          .. s.name:upper()
          .. '_H\n#ifdef __cplusplus\nextern "C" {\n#endif\nint rivet_add(int a, int b);\n#ifdef __cplusplus\n}\n#endif\n#endif\n'
      )
      lib.headers = { 'include/' .. s.name .. '.h' }
      add(
        s,
        files,
        'src/core.c',
        '#include "' .. s.name .. '.h"\nint rivet_add(int a, int b) { return a + b; }\n',
        lib
      )
      if s.kind == 'app' then
        add(
          s,
          files,
          'app/main.c',
          '#include <stdio.h>\n#include "'
            .. s.name
            .. '.h"\nint main(void) { printf("%d\\n", rivet_add(20, 22)); return 0; }\n',
          target(s, s.name, 'executable', nil, { lib.name })
        )
      end
      add(
        s,
        files,
        'tests/core_test.c',
        '#include "'
          .. s.name
          .. '.h"\nint main(void) { return rivet_add(20,22)==42 && rivet_add(-1,1)==0 ? 0 : 1; }\n',
        target(s, s.name .. '_test', 'executable', true, { lib.name })
      )
      add(
        s,
        files,
        'CMakeLists.txt',
        'cmake_minimum_required(VERSION 3.30)\nproject('
          .. s.name
          .. ' LANGUAGES C)\ninclude(CTest)\nset(CMAKE_EXPORT_COMPILE_COMMANDS ON)\ninclude(cmake/RivetTargets.cmake)\n'
      )
      local base =
        require('rivet.languages.cpp').plan({ name = s.name, standard = 17, modules = false })
      files['CMakePresets.json'] = base.files['CMakePresets.json']
      files['.clang-format'] = 'BasedOnStyle: LLVM\n'
      files['.clangd'] = 'CompileFlags:\n  CompilationDatabase: .cache/rivet\n'
    end
    files['README.md'] = '# '
      .. s.name
      .. '\n\n'
      .. P.label
      .. ' project created with Rivet.\n\nRun `:RivetTask test` for the included correctness test and `:RivetTask run` for applications.\nUse `:RivetRunOptions` to select arguments, working directory, and environment.\nNative dependency tools own dependencies and lockfiles; Rivet never resolves them during creation.\n'
    if language == 'python' then
      files['README.md'] = files['README.md']
        .. '\nDefault tasks use an existing .venv, VIRTUAL_ENV, or selected Python without installing packages.\nConfigure creates .venv only on request. Build checks Python syntax; package builds a wheel (requires build).\nRun and test use src on PYTHONPATH. Install with `python -m pip install -e .` to expose the CLI entry point.\nuv projects use explicit `uv sync --inexact` on configure and `uv run --no-sync` thereafter.\n'
    end
    if language == 'swift' then
      files['README.md'] = files['README.md']
        .. '\nOpen Package.swift in Xcode for Apple app integration. Signing, simulators, and SwiftUI previews belong to Xcode.\n'
    end
    return generated(s, files)
  end
  function P.add_file(existing, opts)
    local s = P.normalize(existing)
    local name = identifier(assert(opts.name, 'File name required'), s.edition)
    local files = {}
    local path, text, t
    if language == 'python' then
      path = 'src/' .. s.name .. '/' .. name .. '.py'
      text = '"""' .. name .. ' module."""\n'
    elseif language == 'rust' then
      path = (s.kind == 'workspace' and 'crates/' .. s.name .. '/' or '') .. 'src/' .. name .. '.rs'
      text = '// Declare this module with `mod ' .. name .. ';` in lib.rs or main.rs.\n'
    else
      for _, item in ipairs(s.targets) do
        if item.name == opts.target then
          t = item
        end
      end
      t = t or s.targets[1]
      assert(t, 'Select a target')
      path = language == 'c' and 'src/' .. name .. '.c'
        or (t.test and 'Tests/' or 'Sources/') .. t.name .. '/' .. name .. '.swift'
      text = language == 'c' and ('void ' .. name .. '(void) {}\n')
        or '// Add implementation here.\n'
    end
    add(s, files, path, text, t)
    -- SwiftPM discovers sources in target directories. Adding a source does
    -- not require rewriting Package.swift or relinquishing custom settings.
    return generated(s, files, true)
  end
  function P.add_target(existing, opts)
    local s = P.normalize(existing)
    local name = identifier(assert(opts.name, 'Target name required'), s.edition)
    local files = {}
    assert(
      language ~= 'python',
      'Add a Python module and declare its entry point in pyproject.toml'
    )
    local kind = opts.kind or 'app'
    assert(kind == 'app' or kind == 'library', 'Choose app or library')
    if language == 'rust' then
      assert(kind == 'app', 'Use a Cargo workspace member for additional libraries')
      add(
        s,
        files,
        (s.kind == 'workspace' and 'crates/' .. s.name .. '/' or '') .. 'src/bin/' .. name .. '.rs',
        'fn main() { println!("Hello from ' .. name .. '"); }\n',
        target(s, name, 'executable')
      )
    else
      local t = target(s, name, kind == 'app' and 'executable' or 'static')
      add(
        s,
        files,
        language == 'c' and 'src/' .. name .. '.c'
          or 'Sources/' .. name .. '/' .. (kind == 'app' and 'main' or name) .. '.swift',
        language == 'c'
            and (kind == 'app' and 'int main(void) { return 0; }\n' or 'int ' .. name .. '(void) { return 42; }\n')
          or (kind == 'app' and 'print("Hello")\n' or 'public func answer() -> Int { 42 }\n'),
        t
      )
    end
    return generated(s, files)
  end
  function P.add_dependency()
    error(
      'Use native dependency tools (uv add, cargo add, or edit Package.swift/CMakeLists.txt); review their manifest and lockfile diffs'
    )
  end
  function P.questions(kind, spec)
    if kind == 'new' then
      local kinds = { { id = 'app', label = 'Application' }, { id = 'library', label = 'Library' } }
      if language == 'rust' then
        kinds[#kinds + 1] =
          { id = 'workspace', label = 'Cargo workspace with an application and library' }
      end
      local steps = { { key = 'kind', title = 'Project kind', items = kinds } }
      if language == 'python' then
        steps[#steps + 1] = {
          key = 'manager',
          title = 'Python environment',
          items = {
            { id = 'python', label = 'Python / existing environment' },
            { id = 'uv', label = 'uv (sync explicitly during configure)' },
          },
        }
      end
      if language == 'rust' then
        steps[#steps + 1] = {
          key = 'edition',
          title = 'Rust edition',
          items = { { id = '2024', label = '2024' }, { id = '2021', label = '2021' } },
        }
      end
      if language == 'c' then
        steps[#steps + 1] = {
          key = 'standard',
          title = 'C standard',
          items = {
            { id = 17, label = 'C17' },
            { id = 23, label = 'C23' },
            { id = 11, label = 'C11' },
          },
        }
      end
      return steps
    end
    assert(
      kind ~= 'dependency',
      'Use the native ecosystem dependency manager; Rivet preserves its files'
    )
    local steps = {
      {
        key = 'name',
        title = 'Name (identifier)',
        input = true,
        default = 'feature',
        validate = function(value)
          return identifier(value, spec.edition)
        end,
      },
    }
    if kind == 'target' then
      steps[#steps + 1] = {
        key = 'kind',
        title = 'Target kind',
        items = { { id = 'app', label = 'Application' }, { id = 'library', label = 'Library' } },
      }
    elseif language == 'c' or language == 'swift' then
      steps[#steps + 1] = { key = 'target', title = 'Owning target', items = spec.targets }
    end
    return steps
  end
  if language == 'c' then
    P.lifecycle = function(s, o, c)
      local plan = require('rivet.lifecycle').plan(s, o, c, c_targets)
      plan.spec = P.normalize(plan.spec)
      return plan
    end
  end
  return P
end
return M
