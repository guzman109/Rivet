-- Explicit, previewable conversion of Outset project metadata. No directory-wide rewrite.
local M = {}
local rt = require('rivet.runtime')
local json = require('rivet.json')
local function path_name(path)
  return path == 'cmake/OutsetTargets.cmake' and 'cmake/RivetTargets.cmake' or path
end
local generated_names = {
  ['OUTSET_CLANG_FORMAT'] = 'RIVET_CLANG_FORMAT',
  ['OUTSET_FOUNDATION'] = 'RIVET_FOUNDATION',
  ['OUTSET_METAL'] = 'RIVET_METAL',
  ['OUTSET_METAL_CPP_DIR'] = 'RIVET_METAL_CPP_DIR',
  ['OUTSET_METAL_CPP_INCLUDE'] = 'RIVET_METAL_CPP_INCLUDE',
  ['OUTSET_SANITIZERS'] = 'RIVET_SANITIZERS',
  ['OUTSET_SHADER_DIR'] = 'RIVET_SHADER_DIR',
  ['OUTSET_VULKAN_VALIDATION'] = 'RIVET_VULKAN_VALIDATION',
  ['OUTSET_WARNINGS'] = 'RIVET_WARNINGS',
  ['OUTSET_XCRUN'] = 'RIVET_XCRUN',
}
local function references(text)
  return (
    text
      :gsub('cmake/OutsetTargets%.cmake', 'cmake/RivetTargets.cmake')
      :gsub('%.outset%.local%.json', '.rivet.local.json')
      :gsub('%.outset%.json', '.rivet.json')
      :gsub('%.outset%-recovery', '.rivet-recovery')
      :gsub('%.outset%-lock', '.rivet-lock')
      :gsub('%.cache/outset', '.cache/rivet')
      :gsub('outset_target_options', 'rivet_target_options')
      :gsub('outset_check_std_modules', 'rivet_check_std_modules')
      :gsub('_outset_', '_rivet_')
      :gsub('%f[%w_]OUTSET_[A-Z0-9_]+%f[^%w_]', function(name)
        return generated_names[name] or name
      end)
      :gsub('Generated by Outset', 'Generated by Rivet')
      :gsub('Use Outset or its Lua CLI', 'Use Rivet or its Lua CLI')
  )
end

function M.plan(root)
  root = require('rivet.project').canonical(root)
  assert(
    not rt.exists(rt.confined(root, '.rivet.json')),
    'Project already has a .rivet.json manifest'
  )
  assert(
    not rt.exists(rt.confined(root, '.outset-lock')),
    'An Outset write lock exists; finish that operation first'
  )
  local raw = assert(rt.read(rt.confined(root, '.outset.json')), 'No Outset manifest to migrate')
  local spec = json.decode(raw)
  require('rivet.model').normalize(spec)
  local plan = { root = root, spec = spec, files = {}, expected = {}, moves = {} }
  local backup = '.rivet-recovery/outset-' .. os.date('%Y%m%d-%H%M%S')
  local function write(path, content)
    local existing = rt.read(rt.confined(root, path))
    assert(existing == nil or content == false or existing ~= content, 'Unchanged migration write')
    plan.files[path], plan.expected[path] = content, existing or false
    if existing then
      local saved = backup .. '/' .. path
      assert(not rt.exists(rt.confined(root, saved)), 'Migration backup already exists: ' .. saved)
      plan.files[saved], plan.expected[saved] = existing, false
    end
  end
  local function move(from, to, content)
    assert(not rt.exists(rt.confined(root, to)), 'Migration destination exists: ' .. to)
    write(from, false)
    write(to, content)
    plan.moves[from] = to
  end
  local candidates = { ['CMakeUserPresets.json'] = true, ['.gitignore'] = true, ['.clangd'] = true }
  for index, path in ipairs(spec.files or {}) do
    candidates[path] = true
    spec.files[index] = path_name(path)
  end
  for path in pairs(candidates) do
    local text = rt.read(rt.confined(root, path))
    if text then
      local updated = references(text)
      if path_name(path) ~= path then
        move(path, path_name(path), updated)
      elseif text ~= updated then
        write(path, updated)
      end
    end
  end
  local generated = {}
  for path, content in pairs(spec.generated or {}) do
    generated[path_name(path)] = references(content)
  end
  spec.generated = generated
  local local_options = rt.read(rt.confined(root, '.outset.local.json'))
  if local_options then
    move('.outset.local.json', '.rivet.local.json', local_options)
  end
  move('.outset.json', '.rivet.json', json.encode(spec))
  plan.notes = {
    'Reconfigure after migration to refresh CMake and clangd paths.',
    'Original changed files are retained under ' .. backup .. '.',
    'Review any remaining Outset references in your own scripts and documentation.',
  }
  return plan
end
return M
